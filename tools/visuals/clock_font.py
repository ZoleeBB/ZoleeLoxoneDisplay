"""A hőmérséklet és a készenléti óra külön súlyú, szűkített LVGL-betűkészletei."""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]


def generate(source, standby=False):
    size = 132
    alphabet = " 0123456789-:" if standby else " 0123456789-:°"
    codepoints = sorted(set(map(ord, alphabet)))
    out = ROOT / 'main/fonts'
    out.mkdir(parents=True, exist_ok=True)
    fingerprint = hashlib.sha256(source.read_bytes()).hexdigest()
    with TTFont(source) as face:
        weight = face['OS/2'].usWeightClass
        if standby and weight != 600:
            raise ValueError(f"Standby requires the semibold (600) font, received {weight}")
        supported = face.getBestCmap()
        for cp in codepoints:
            if cp not in supported:
                raise ValueError(f"Missing glyph U+{cp:04X}")
    font = ImageFont.truetype(str(source), size)
    bounds = [font.getbbox(chr(cp), anchor='ls') for cp in codepoints]
    ascent = -min(box[1] for box in bounds)
    descent = max(box[3] for box in bounds)
    bitmap = []
    descriptors = ['    {0}, /* reserved glyph 0 */']
    for cp, (left, top, right, bottom) in zip(codepoints, bounds):
        width, height = right-left, bottom-top
        start = len(bitmap)
        if width and height:
            img = Image.new('L', (width, height))
            ImageDraw.Draw(img).text((-left, -top), chr(cp), font=font, fill=255, anchor='ls')
            pixels = [(v*15+127)//255 for v in img.tobytes()]
            if len(pixels) % 2:
                pixels.append(0)
            bitmap.extend((pixels[i]<<4) | pixels[i+1] for i in range(0, len(pixels), 2))
        descriptors.append('    {.bitmap_index=%d, .adv_w=%d, .box_w=%d, .box_h=%d, .ofs_x=%d, .ofs_y=%d}, /* U+%04X */' %
                           (start, round(font.getlength(chr(cp))*16), width, height, left, -bottom, cp))
    rows = ['    '+','.join(f'0x{b:02x}' for b in bitmap[i:i+24])+',' for i in range(0, len(bitmap), 24)]
    unicode_list = ','.join(str(cp-32) for cp in codepoints)
    name = f'app_font_standby_{size}' if standby else f'app_font_numbers_{size}'
    license_note = ('Open Sans Semibold, digitized data copyright 2010–2011 Google Corporation '
                    '(OpenSans-Apache-2.0.txt).' if standby else
                    'DejaVu Sans ExtraLight (DejaVu-LICENSE.txt).')
    text = f'''/* Generated by tools/visuals/clock_font.py; source SHA256 {fingerprint}.
 * {license_note} */
#include "lvgl.h"
static const uint8_t bitmap[] = {{
{chr(10).join(rows)}
}};
static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {{
{chr(10).join(descriptors)}
}};
static const uint16_t unicode_list[] = {{{unicode_list}}};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{{{
    .range_start=32, .range_length={codepoints[-1]-32+1}, .glyph_id_start=1,
    .unicode_list=unicode_list, .glyph_id_ofs_list=NULL,
    .list_length={len(codepoints)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
}}}};
static const lv_font_fmt_txt_dsc_t data = {{
    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=cmaps,
    .kern_dsc=NULL, .kern_scale=0, .cmap_num=1, .bpp=4,
    .kern_classes=0, .bitmap_format=0
}};
const lv_font_t {name} = {{
    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
    .line_height={ascent+descent+2}, .base_line={descent+1},
    .subpx=LV_FONT_SUBPX_NONE, .underline_position=-1, .underline_thickness=1,
    .dsc=&data
}};
'''
    (out/f'{name}.c').write_text(text)
    print(f'Generated {name} with {len(codepoints)} glyphs.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('font', type=Path)
    parser.add_argument('--standby', action='store_true', help="Generate the semibold clock digits")
    args = parser.parse_args()
    generate(args.font, standby=args.standby)
